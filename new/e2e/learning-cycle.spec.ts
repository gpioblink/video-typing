import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { mockYouTube } from './playerDouble';

const typing = (page: import('@playwright/test').Page) => page.getByRole('region', { name: 'Typing', exact: true });
const keyboard = (page: import('@playwright/test').Page) => typing(page).locator('[tabindex="0"]');
const history = (page: import('@playwright/test').Page) => page.getByRole('region', { name: '学習履歴', exact: true });

const config = (page: import('@playwright/test').Page) => page.getByRole('region', { name: 'Config', exact: true });
async function openShortPractice(page: import('@playwright/test').Page) {
  await page.getByLabel('操作チュートリアル', { exact: true }).uncheck();
  await page.getByText('好きなYouTube動画で遊ぶ', { exact: true }).click();
  await page.getByLabel('YouTube URL', { exact: true }).fill('https://www.youtube.com/watch?v=eRsGyueVLvQ');
  await page.getByLabel('字幕ファイル', { exact: true }).setInputFiles(resolve('public/captions/sintel-en.srt'));
  await page.getByRole('button', { name: '区間を選ぶ', exact: true }).click();
  await page.getByLabel('開始秒', { exact: true }).fill('107');
  await page.getByLabel('終了秒', { exact: true }).fill('111.5');
  await page.getByRole('button', { name: '開く', exact: true }).click();
}

test('listen, resume, learn unknown meaning, export Anki, review and retry updates learning state', async ({ page }) => {
  await mockYouTube(page); await page.goto('/');
  await page.getByText('辞書設定', { exact: true }).click();
  await page.getByLabel('辞書TSV').setInputFiles({ name: 'test.tsv', mimeType: 'text/tab-separated-values', buffer: Buffer.from('This\tOriginal demonstration meaning.\n') });
  await expect(page.getByRole('alert')).toContainText('辞書 1 件');
  await openShortPractice(page);
  const subtitle = page.getByRole('region', { name: 'Subtitle', exact: true });
  await expect(subtitle).toContainText('This blade has a dark past.');
  await subtitle.getByRole('button', { name: 'Subtitleを閉じる', exact: true }).click();
  await expect(subtitle).toHaveCount(0);
  await config(page).getByRole('button', { name: 'Configを開く' }).click();
  await config(page).getByRole('button', { name: '字幕ウィンドウを表示', exact: true }).click();
  await config(page).getByLabel('再生速度', { exact: true }).selectOption('0.75');
  await expect.poll(() => page.evaluate(() => (window as any).testPlayer.getPlaybackRate())).toBe(0.75);
  await config(page).getByLabel('再生速度', { exact: true }).selectOption('1');
  await config(page).getByRole('button', { name: 'Configを折りたたむ' }).click();
  await keyboard(page).focus(); await keyboard(page).pressSequentially('Th');
  await expect(keyboard(page).locator('.finished')).toHaveCount(2);
  await page.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await expect(history(page)).toContainText('完了 0 / 1 問');
  await page.reload();
  await history(page).getByRole('button', { name: '続きから開く', exact: true }).click();
  await expect(keyboard(page).locator('.finished')).toHaveCount(2);
  await page.evaluate(() => (window as any).testPlayer.pauseVideo());
  await keyboard(page).locator('.finished').first().click();
  const hints = page.getByRole('region', { name: 'Hint', exact: true });
  await expect(hints.locator('.selectable').filter({ hasText: 'Original demonstration meaning.' })).toContainText('Original demonstration meaning.');
  await hints.locator('.selectable').filter({ hasText: 'Original demonstration meaning.' }).click();
  await expect(keyboard(page).getByText('ignorance', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await expect(history(page)).toContainText('知らなかった単語 1 件');
  const downloaded = page.waitForEvent('download');
  await history(page).getByRole('button', { name: 'Anki用TSV出力', exact: true }).click();
  const file = await downloaded; const text = readFileSync((await file.path())!, 'utf8');
  expect(text).toContain('#separator:Tab'); expect(text).toContain('Original demonstration meaning.'); expect(text).toContain('youtube.com/watch?');
  await history(page).getByRole('button', { name: '復習する', exact: true }).click();
  await expect(keyboard(page).locator('.finished')).toHaveCount(0);
  await keyboard(page).focus(); await keyboard(page).pressSequentially('Thisbladehasadarkpast', { delay: 20 });
  await expect(keyboard(page).getByText('ignorance', { exact: true })).toHaveCount(0);
  await page.evaluate(() => (window as any).testPlayer.seekTo(110.5));
  await expect(page.getByRole('heading', { name: 'クリップ完走', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'クリップ選択へ', exact: true }).click();
  await expect(history(page)).toContainText('復習 0 問');
  await expect(history(page).getByRole('button', { name: '復習する', exact: true })).toBeDisabled();
  await expect(history(page).getByRole('button', { name: 'Anki用TSV出力', exact: true })).toBeDisabled();
  await history(page).getByRole('button', { name: '最初から再挑戦', exact: true }).click();
  await expect(keyboard(page).locator('.finished')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => (window as any).testPlayer?.cue?.startSeconds)).toBe(107);
  await expect.poll(() => page.evaluate(() => (window as any).testPlayer?.cue?.endSeconds)).toBe(111.5);
  await page.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await page.reload();
  await expect(history(page)).toContainText('完了 0 / 1 問');
});

test('a stale history view cannot restore or export a word solved in another tab', async ({ page, context }) => {
  await mockYouTube(page); await page.goto('/');
  await page.getByText('辞書設定', { exact: true }).click();
  await page.getByLabel('辞書TSV').setInputFiles({ name: 'test.tsv', mimeType: 'text/tab-separated-values', buffer: Buffer.from('This\tOriginal meaning.\n') });
  await openShortPractice(page);
  await expect(keyboard(page).locator('.available')).toBeVisible();
  await keyboard(page).locator('.available').click();
  await page.getByRole('region', { name: 'Hint', exact: true }).locator('.selectable').filter({ hasText: 'Original meaning.' }).click();
  await page.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await expect(history(page)).toContainText('知らなかった単語 1 件');
  const second = await context.newPage(); await mockYouTube(second); await second.goto('/');
  await history(second).getByRole('button', { name: '復習する', exact: true }).click();
  await expect(keyboard(second).locator('.available')).toBeVisible();
  await keyboard(second).focus(); await keyboard(second).pressSequentially('Thisbladehasadarkpast', { delay: 20 });
  await expect(keyboard(second).getByText('ignorance', { exact: true })).toHaveCount(0);
  await second.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await expect(history(second)).toContainText('復習 0 問');
  await page.bringToFront();
  await history(page).getByRole('button', { name: '復習する', exact: true }).click();
  await expect(history(page).getByRole('alert')).toContainText('復習する問題はありません');
  await expect(typing(page)).toHaveCount(0);
  let downloads = 0; page.on('download', () => downloads++);
  await history(page).getByRole('button', { name: 'Anki用TSV出力', exact: true }).click();
  await expect(history(page)).toContainText('現在の復習対象はありません');
  await expect(history(page).getByRole('button', { name: 'Anki用TSV出力', exact: true })).toBeDisabled();
  expect(downloads).toBe(0);
  await second.close();
});

test('recommendation history restores Japanese captions together with English typing progress', async ({ page }) => {
  await mockYouTube(page); await page.goto('/');
  await page.getByLabel('操作チュートリアル', { exact: true }).uncheck();
  await page.getByRole('button', { name: /Sintel - Open Movie/ }).click();
  const subtitle = page.getByRole('region', { name: 'Subtitle', exact: true });
  await expect(subtitle.getByRole('button', { name: '日本語', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(() => (window as any).testPlayer.seekTo(108));
  await expect(subtitle.locator('[data-subtitle-text]')).toContainText(/[\u3040-\u30ff\u4e00-\u9fff]/);
  const japanese = await subtitle.locator('[data-subtitle-text]').innerText();
  await keyboard(page).focus(); await keyboard(page).pressSequentially('Th');
  await expect(keyboard(page).locator('.finished')).toHaveCount(2);
  await page.getByRole('button', { name: 'クリップ選択に戻る', exact: true }).click();
  await history(page).getByRole('button', { name: '続きから開く', exact: true }).click();
  await expect(keyboard(page).locator('.finished')).toHaveCount(2);
  await expect(subtitle.getByRole('button', { name: '日本語', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(subtitle.locator('[data-subtitle-text]')).toHaveText(japanese);
  await subtitle.getByRole('button', { name: '英語（答え）', exact: true }).click();
  await expect(subtitle.locator('[data-subtitle-text]')).toHaveText('This blade has a dark past.');
});
